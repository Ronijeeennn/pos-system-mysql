<div class="card">
    <h1>About This Project</h1>
    <p>
        This project is a laboratory activity for building the first version of a
        basic Point-of-Sale (POS) system using the <strong>CodeIgniter 4</strong> PHP framework.
    </p>
    <h2>Current Scope</h2>
    <ul>
        <li>A landing page and an about page</li>
        <li>A Customer Accounts page listing customer records (full name, email, phone)</li>
        <li>A User Accounts page listing user/staff records (avatar, username, full name)</li>
        <li>Data for the Customer and User Accounts pages is stored in a MySQL database and
            retrieved through CodeIgniter Models (<code>CustomerModel</code> and
            <code>UserModel</code>)</li>
        <li>Forms to create and edit customers and users, with server-side validation</li>
        <li>Avatar upload for users (JPG or PNG, up to 2 MB), saved as a 200 &times; 200 thumbnail</li>
    </ul>
    <h2>Planned Next Steps</h2>
    <ul>
        <li>Add delete functionality for customers and users</li>
        <li>Add authentication for staff accounts</li>
    </ul>
</div>
